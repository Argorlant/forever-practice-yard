// Writes the talent trees part of src/specs/<class>/talents.gen.ts from
// research/<class>_forever.json (talents.tsSnippet: TREES, NAMES,
// NEW_IN_FOREVER in gunba's tree order, which decodes the sims' strings).
//
// Usage: node tools/gen_talents.mjs mage "Arcane,Fire,Frost"
import fs from 'node:fs';

const [cls, treeNames] = process.argv.slice(2);
if (!cls || !treeNames) throw new Error('usage: node tools/gen_talents.mjs <class> "<Tree 1>,<Tree 2>,<Tree 3>"');
const json = JSON.parse(fs.readFileSync(`research/${cls}_forever.json`, 'utf8'));
const { TREES, NAMES, NEW_IN_FOREVER } = json.talents.tsSnippet;
const q = (s) => `'${String(s).replace(/'/g, "\\'")}'`;
const lines = [
  `// Generated by tools/gen_talents.mjs from research/${cls}_forever.json. Do not edit by hand.`,
  `// Order: gunba's current tree (the order the sims' talent strings use).`,
  `export const TREE_NAMES = [${treeNames.split(',').map((t) => q(t.trim())).join(', ')}];`,
  '',
  'export const TREES = [',
  ...TREES.map((tree) => `  [${tree.map(q).join(', ')}],`),
  '] as const;',
  '',
  'export type TalentKey = (typeof TREES)[number][number];',
  'export type Talents = Record<TalentKey, number>;',
  '',
  'export const NAMES: Record<TalentKey, string> = {',
  ...Object.entries(NAMES).map(([k, v]) => `  ${k}: ${q(v)},`),
  '};',
  '',
  `export const NEW_IN_FOREVER = new Set<TalentKey>([${NEW_IN_FOREVER.map(q).join(', ')}]);`,
  '',
];
fs.mkdirSync(`src/specs/${cls}`, { recursive: true });
fs.writeFileSync(`src/specs/${cls}/talents.gen.ts`, lines.join('\n'));
console.log(`src/specs/${cls}/talents.gen.ts: ${TREES.map((t) => t.length).join('/')} talents`);
