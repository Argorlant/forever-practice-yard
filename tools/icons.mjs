// Downloads the game-icons.net drawings (CC BY 3.0) and generates
// src/ui/icons.gen.ts with each icon's path data and author, for the credits.
//
// Usage: node tools/icons.mjs
import fs from 'node:fs';

// Only what has no WoW icon: the target portrait of the training dummy.
const ICONS = {
  dummy: 'lorc/target-dummy',
};

const out = [];
const authors = new Set();
for (const [key, file] of Object.entries(ICONS)) {
  const url = `https://raw.githubusercontent.com/game-icons/icons/master/${file}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  const svg = await res.text();
  // Every SVG has a black background square and the drawing in white; keep
  // only the drawing.
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)]
    .map((m) => m[1])
    .filter((d) => !/^M0 0h512v512H0z$/.test(d.trim()));
  if (!paths.length) throw new Error(`${file}: no paths`);
  const author = file.split('/')[0];
  authors.add(author);
  out.push(`  ${key}: { author: '${author}', name: '${file.split('/')[1]}', d: ${JSON.stringify(paths.join(' '))} },`);
  process.stdout.write('.');
}

const ts = `// Generated by tools/icons.mjs from https://game-icons.net (CC BY 3.0).
// Do not edit by hand.
export interface IconData { author: string; name: string; d: string }
export const ICONS: Record<string, IconData> = {
${out.join('\n')}
};
export const ICON_AUTHORS = ${JSON.stringify([...authors].sort())};
`;
fs.writeFileSync('src/ui/icons.gen.ts', ts);
console.log(`\n${out.length} icons by ${[...authors].join(', ')}`);
